import Container from '@mui/material/Container';
import type { EditorialChapter, EditorialDocument, EditorialReference } from '@/src/content/editorial.mjs';
import { portfolioMessages } from '@/src/content/portfolio.mjs';
import type { VisualAsset } from '@/src/content/visuals.mjs';
import { useLocale } from '@/src/i18n/context';
import { AppLinkAtom } from '../AppLink.atom';
import { GoToContactFormMolecule } from '../GoToContactForm.molecule';
import { InfoTextBlockMolecule } from '../InfoTextBlock.molecule';
import { LinkButtonAtom } from '../LinkButton.atom';
import { RichTextAtom } from '../RichText.atom';
import { EditorialExhibitMolecule } from './EditorialExhibit.molecule';
import styles from './editorial.module.scss';

type Entry = {term: string; detail: string};

function Artwork({asset, priority = false, inline = false, cover = false}: {asset: VisualAsset; priority?: boolean; inline?: boolean; cover?: boolean}) {
    return <figure className={`${styles.artwork} ${inline ? styles.inlineArtwork : ''} ${asset.kind === 'photo' ? styles.photo : styles.illustration}`} data-asset={asset.id} data-editorial-cover={cover ? "true" : undefined}>
        <picture>
            {asset.mobile && <source media="(max-width: 599px)" srcSet={asset.mobile.src} width={asset.mobile.width} height={asset.mobile.height}/>}
            {/* Static derivatives are generated by the visual manifest. */}
            <img src={asset.src} srcSet={asset.srcSet} sizes={asset.srcSet ? (inline ? '(max-width: 599px) min(200px, calc(100vw - 64px)), 200px' : '(max-width: 599px) calc(100vw - 64px), (max-width: 899px) calc(100vw - 96px), 1152px') : undefined}
                width={asset.width} height={asset.height} alt={asset.alt} loading={priority ? 'eager' : 'lazy'} fetchPriority={priority ? 'high' : undefined} decoding="async"/>
        </picture>
        {asset.credit && <figcaption>{asset.credit}</figcaption>}
    </figure>;
}

function References({entries, format}: {entries: Entry[]; format: EditorialReference}) {
    if (!entries.length) return null;
    if (format === 'table') return <table className={styles.referenceTable}><tbody>{entries.map((entry, index) => <tr key={`${entry.term}-${index}`}><th scope="row"><RichTextAtom text={entry.term}/></th><td><RichTextAtom text={entry.detail}/></td></tr>)}</tbody></table>;
    return <dl className={`${styles.references} ${styles[`reference_${format}`]}`}>{entries.map((entry, index) => <div key={`${entry.term}-${index}`}><dt><RichTextAtom text={entry.term}/></dt><dd><RichTextAtom text={entry.detail}/></dd></div>)}</dl>;
}

function Chapter({chapter, cover, role}: {chapter: EditorialChapter; cover: VisualAsset | null; role: {label: string; text: string} | null}) {
    const exhibit = chapter.exhibit && <EditorialExhibitMolecule exhibit={chapter.exhibit}/>;
    const canHaveRail = chapter.layout === 'aside' || chapter.layout === 'split';
    const railCover: VisualAsset | null = canHaveRail ? cover : null;
    const hasRail = canHaveRail && Boolean(railCover || (chapter.exhibitPosition === 'aside' && exhibit));
    const items = chapter.items.length > 0 && <dl className={styles.chapterItems}>{chapter.items.map((item, index) => <div key={`${item.title}-${index}`}><dt><RichTextAtom text={item.title}/></dt><dd><RichTextAtom text={item.description}/></dd></div>)}</dl>;
    return <section className={`${styles.chapter} ${styles[`layout_${chapter.layout}`]}`} data-editorial-chapter={chapter.id} data-layout={chapter.layout} aria-labelledby={chapter.id}>
        {chapter.anchors.filter(anchor => anchor !== chapter.id).map(anchor => <span id={anchor} className={styles.anchor} key={anchor}/>)}
        <h2 id={chapter.id} tabIndex={-1}>{chapter.title}</h2>
        {chapter.note && <p className={styles.chapterNote}><RichTextAtom text={chapter.note}/></p>}
        {cover && !railCover && <Artwork asset={cover} cover/>}
        {chapter.exhibitPosition === 'before' && exhibit}
        <div className={`${styles.chapterContent} ${hasRail ? styles.hasRail : ''}`}>
            <div className={styles.prose}>
                {chapter.paragraphs.map(paragraph => <div className={`${styles.paragraphGroup} ${paragraph.media.length > 0 && paragraph.media.every(media => media.variant === 'inline') ? styles.withInlineMedia : ''}`} key={paragraph.key}>
                    <p><RichTextAtom text={paragraph.text}/></p>
                    {paragraph.media.map((media, index) => <Artwork key={`${media.asset.src}-${index}`} asset={media.asset} inline={media.variant === 'inline'}/>)}
                </div>)}
                {role && <div className={styles.role}><h3>{role.label}</h3><p><RichTextAtom text={role.text}/></p></div>}
                {hasRail && items}
            </div>
            {railCover ? <div className={styles.chapterRail}><Artwork asset={railCover} cover/>{chapter.exhibitPosition === 'aside' && exhibit}</div> : chapter.exhibitPosition === 'aside' && exhibit}
        </div>
        {!hasRail && items}
        <References entries={chapter.facts} format={chapter.reference}/>
        {chapter.exhibitPosition === 'after' && exhibit}
    </section>;
}

export function EditorialArticle({document, title, artwork}: {document: EditorialDocument; title: string; artwork: VisualAsset | null}) {
    const {locale, messages} = useLocale();
    const labels = portfolioMessages[locale];
    const openingCover = document.cover === 'opening' && artwork;
    const role = document.role ? {label: labels.role, text: document.role} : null;
    const panoramaOpening = document.opening === 'panorama' && Boolean(openingCover);
    const openingIntro = panoramaOpening ? document.intro.slice(0, 1) : document.intro;
    const followingIntro = panoramaOpening ? document.intro.slice(1) : [];
    const contentsLabel = locale === 'pl' ? 'Spis treści' : 'Contents';
    const navigation = <nav className={`${styles.toc} ${styles[`toc_${document.toc}`]}`} aria-label={contentsLabel} data-editorial-toc>
        <span>{contentsLabel}</span><ul>{document.chapters.map(chapter => <li key={chapter.id}><a href={`#${chapter.id}`}>{chapter.title}</a></li>)}</ul>
    </nav>;
    return <Container className={styles.container}>
        <article className={styles.article} data-editorial-opening={document.opening}>
            <header className={`${styles.opening} ${styles[`opening_${document.opening}`]} ${!openingCover ? styles.openingNoCover : ''}`}>
                <div className={styles.openingCopy}>
                    <div className={styles.openingTitle}>
                        <h1>{title}</h1>
                        {document.kind === 'project' && <div className={styles.meta}><span>{document.category}</span><span>{labels.confidential}</span></div>}
                    </div>
                    <div className={styles.openingNarrative}>
                        <div className={styles.intro}>{openingIntro.map((paragraph, index) => <p key={index}><RichTextAtom text={paragraph}/></p>)}</div>
                        {document.audience && <dl className={styles.audience}><dt>{labels.audience}</dt><dd><RichTextAtom text={document.audience}/></dd></dl>}
                        {document.roleAt === 'opening' && role && <div className={styles.role}><h2>{role.label}</h2><p><RichTextAtom text={role.text}/></p></div>}
                        {document.kind === 'service' && <AppLinkAtom className={styles.introLink} href={`/contact/?about=${encodeURIComponent(title)}`}>{messages.introContact}</AppLinkAtom>}
                    </div>
                </div>
                {openingCover && <Artwork asset={openingCover} priority cover/>}
                {followingIntro.length > 0 && <div className={`${styles.intro} ${styles.followingIntro}`}>{followingIntro.map((paragraph, index) => <p key={index}><RichTextAtom text={paragraph}/></p>)}</div>}
            </header>
            {document.toc === 'inline' && navigation}
            <div className={`${styles.articleBody} ${document.toc === 'rail' ? styles.withRail : ''}`}>
                {document.toc === 'rail' && navigation}
                <div className={styles.chapters}>{document.chapters.map(chapter => <Chapter key={chapter.id} chapter={chapter} cover={document.cover === chapter.id ? artwork : null} role={document.roleAt === chapter.id ? role : null}/>)}</div>
            </div>
            {document.stack.length > 0 && <section className={styles.stack} aria-labelledby="editorial-stack-title"><h2 id="editorial-stack-title">{labels.stack}</h2><References entries={document.stack} format={document.reference}/></section>}
            {document.kind === 'service' ? <footer className={styles.footer}>
                <aside className="related-services"><h2>{messages.relatedIntro}</h2><InfoTextBlockMolecule items={document.related.map(link => ({heading: link.title, content: <LinkButtonAtom href={link.path}>{messages.readMore}</LinkButtonAtom>}))}/></aside>
                <GoToContactFormMolecule objectOfInterest={title}/>
            </footer> : <footer className={`${styles.footer} ${styles.projectFooter}`}>
                <AppLinkAtom href={`/contact/?about=${encodeURIComponent(title)}`} className={styles.actionLink}>{labels.contact}</AppLinkAtom>
                <aside className={styles.related}><h2>{labels.related}</h2><ul>{document.related.map(link => <li key={link.path}><AppLinkAtom href={link.path}>{link.title}</AppLinkAtom></li>)}</ul></aside>
                <nav className={styles.neighbors} aria-label={labels.navigation}>
                    <div>{document.previous && <AppLinkAtom href={document.previous.path}><span>{labels.previous}</span><strong>{document.previous.title}</strong></AppLinkAtom>}</div>
                    <div>{document.next && <AppLinkAtom href={document.next.path}><span>{labels.next}</span><strong>{document.next.title}</strong></AppLinkAtom>}</div>
                </nav>
                <AppLinkAtom href={`/portfolio/#${document.projectId}`} className={styles.allLink}>{labels.all}</AppLinkAtom>
            </footer>}
        </article>
    </Container>;
}
