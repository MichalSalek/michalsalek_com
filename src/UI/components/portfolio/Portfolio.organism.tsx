import Container from '@mui/material/Container';
import Typography from '@mui/material/Typography';
import type { PortfolioCard } from '@/src/content/load-page';
import { portfolioMessages } from '@/src/content/portfolio.mjs';
import type { VisualAsset } from '@/src/content/visuals.mjs';
import { useLocale } from '@/src/i18n/context';
import { AppLinkAtom } from '../AppLink.atom';
import {ActionLinkAtom} from '../ActionLink.atom';
import {ContactSection} from '../ContactSection.organism';
import styles from './portfolio.module.scss';

function Artwork({asset, priority = false, hero = false}: {asset: VisualAsset; priority?: boolean; hero?: boolean}) {
    return <figure className={hero ? styles.heroArtwork : styles.artwork} data-asset={asset.id}>
        {/* Responsive static derivatives are generated by the visual manifest. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={asset.src} srcSet={asset.srcSet} sizes={asset.srcSet ? (hero ? '(max-width: 599px) calc(100vw - 64px), (max-width: 899px) calc(100vw - 96px), 960px' : '(max-width: 599px) calc(100vw - 98px), (max-width: 699px) calc(100vw - 130px), 320px') : undefined}
            width={asset.width} height={asset.height} alt={asset.alt} loading={priority ? 'eager' : 'lazy'}
            fetchPriority={priority ? 'high' : undefined} decoding="async"/>
        {asset.credit && <figcaption>{asset.credit}</figcaption>}
    </figure>;
}

export function PortfolioList({cards, compact = false, priorityFirst = false}: {cards: PortfolioCard[]; compact?: boolean; priorityFirst?: boolean}) {
    const {locale} = useLocale();
    const labels = portfolioMessages[locale];
    return <div className={`${styles.list} ${compact ? styles.compact : ''}`}>
        {cards.map((card, index) => <article className={styles.row} id={card.id} key={card.id}>
            <AppLinkAtom href={card.path} className={styles.card}>
                <Artwork asset={card.artwork} priority={priorityFirst && index === 0}/>
                <div className={styles.cardCopy}>
                    <h2>{card.title}</h2>
                    <div className={styles.meta}><span>{card.category}</span><span>{labels.confidential}</span></div>
                    <p>{card.summary}</p>
                    <span className={styles.read}>{labels.read}<span aria-hidden="true"> →</span></span>
                </div>
            </AppLinkAtom>
        </article>)}
    </div>;
}

export function PortfolioIndexPage({cards}: {cards: PortfolioCard[]}) {
    const {locale} = useLocale();
    const labels = portfolioMessages[locale];
    return <Container className={styles.page}>
        <header className={styles.indexHeader}>
            <Typography variant="h1" component="h1">Portfolio</Typography>
            <p className={styles.lead}>{labels.introduction}</p>
            <p className={styles.confidentiality}>{labels.confidentiality}</p>
        </header>
        <PortfolioList cards={cards} priorityFirst/>
        <ContactSection/>
    </Container>;
}

export function PortfolioShowcase({cards}: {cards: PortfolioCard[]}) {
    const {locale} = useLocale();
    const labels = portfolioMessages[locale];
    return <Container component="section" className={styles.showcase} aria-labelledby="portfolio-showcase-title">
        <header className={styles.showcaseHeader}>
            <Typography variant="h2" component="h2" id="portfolio-showcase-title">{labels.selected}</Typography>
            <p className={styles.lead}>{labels.selectedIntro}</p>
        </header>
        <PortfolioList cards={cards.slice(0, 3)} compact/>
        <ActionLinkAtom href="/portfolio/">{labels.all}</ActionLinkAtom>
    </Container>;
}
